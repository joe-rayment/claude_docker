#!/usr/bin/env bash
# sshd-lib.sh -- the container's sshd, as a sourceable library (no top-level
# side effects: sourcing defines functions and nothing else).
#
# Sourced by scripts/container/entrypoint.sh (the piece that wires it in) and
# by tests/container-sshd.bats. Runs only in the image (or natively in the
# tests), so it is not bound by the Mac side's bash 3.2 rule -- but it uses
# nothing newer than bash 4 anyway. If the sourcing script defines log(), the
# library reports through it; otherwise it prints to stderr.
#
# Functions (return 0 on success, non-zero on failure unless noted):
#   cdev_sshd_config <runtime_dir> <project_dir> <port> <allow_user> <force_command>
#       prints the sshd_config text on stdout; the caller writes it mode 600.
#       ForceCommand is single-quoted (sshd hands it to the user's shell -c);
#       HostKey/PidFile/AuthorizedKeysFile are double-quoted when the path
#       holds whitespace.
#   cdev_env_snapshot <out_file>
#       writes `export K='v'` lines for the current environment (mode 600;
#       the caller chowns it). Drops noise names, HOME is forced to
#       $AGENT_HOME when set, and a value containing sk-or-v1- is dropped
#       with only its NAME logged to stderr.
#   cdev_host_link <host_path> <project_dir>
#       makes <$CLAUDE_ORCA_HOST_LINK_ROOT><host_path> a symlink to
#       <project_dir> (the Mac project path resolving inside the container).
#       NEVER fatal: every refusal is one log line and return 0.
#   cdev_host_key_fpr <pubkey_file>
#       prints SHA256:<b64> exactly as `ssh-keygen -lf` would.
#   cdev_sshd_probe <port>
#       0 when 127.0.0.1:<port> answers a line starting SSH-2.0- within 2 s.
#   cdev_sshd_loop <sshd_bin> <cfg> <log> <ready_file> <port> <fpr> [launcher...]
#       foreground restart loop, meant to be run with `&`. sshd_bin must be an
#       ABSOLUTE path (sshd re-execs itself). Any extra words after <fpr> are a
#       launcher prefix, run as `launcher... sshd_bin -D -e -f cfg` -- the
#       entrypoint passes `agent_exec` when privilege drop is on, so $! of the
#       background launcher stays the real sshd pid. TERM/INT kills the sshd
#       child, removes the ready file and exits 0.

# One log line: through the caller's log() when it has one.
_cdev_sshd_note() {
  if declare -F log >/dev/null 2>&1; then log "$*"; else printf '%s\n' "$*" >&2; fi
}

# Quote a config word: bare unless it holds whitespace or a double quote.
_cdev_sshd_q() {
  local s=$1
  case $s in
    *[[:space:]\"]*) s=${s//\\/\\\\}; s=${s//\"/\\\"}; printf '"%s"' "$s" ;;
    *) printf '%s' "$s" ;;
  esac
}

cdev_sshd_config() {
  local rt=$1 proj=$2 port=$3 user=$4 fc=$5
  local sq="'\\''"
  fc=${fc//\'/$sq}
  printf '%s\n' \
    '# generated by scripts/container/sshd-lib.sh -- do not edit; rewritten on every boot' \
    "Port $port" \
    'ListenAddress 0.0.0.0' \
    "HostKey $(_cdev_sshd_q "$rt/ssh/host_ed25519")" \
    "PidFile $(_cdev_sshd_q "$rt/sshd.pid")" \
    "AuthorizedKeysFile $(_cdev_sshd_q "$proj/.claude-dev/state/ssh/authorized_keys")" \
    'PubkeyAuthentication yes' \
    'PasswordAuthentication no' \
    'KbdInteractiveAuthentication no' \
    'UsePAM no' \
    'StrictModes no' \
    "AllowUsers $user" \
    'PermitRootLogin no' \
    'AllowTcpForwarding no' \
    'X11Forwarding no' \
    'AllowAgentForwarding no' \
    'PermitTunnel no' \
    'AllowStreamLocalForwarding remote' \
    'StreamLocalBindUnlink yes' \
    'PermitUserEnvironment no' \
    'PrintMotd no' \
    'AcceptEnv TERM_PROGRAM TERM_PROGRAM_VERSION COLORTERM CDEV_CWD LANG LC_*' \
    "ForceCommand '$fc'" \
    'LogLevel INFO'
}

cdev_env_snapshot() {
  local out=$1 tmp name val q="'\\''" home
  tmp="$out.tmp.$$"
  home=${AGENT_HOME:-${HOME:-}}
  (
    umask 077
    {
      printf '# generated by scripts/container/sshd-lib.sh -- the boot environment, for ssh panes\n'
      while IFS= read -r name; do
        [[ $name =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
        case $name in
          HOME|TERM|SHLVL|PWD|OLDPWD|_|SSH_*|TERM_PROGRAM*|COLORTERM|CDEV_*|USER|LOGNAME|SHELL|MAIL) continue ;;
        esac
        val=${!name-}
        if [[ $val == *sk-or-v1-* ]]; then
          printf 'cdev_env_snapshot: dropped %s (value looks like an OpenRouter key)\n' "$name" >&2
          continue
        fi
        printf "export %s='%s'\n" "$name" "${val//\'/$q}"
      done < <(compgen -e | LC_ALL=C sort)
      [ -n "$home" ] && printf "export HOME='%s'\n" "${home//\'/$q}"
      :
    } >"$tmp"
  ) || { rm -f "$tmp"; return 1; }
  chmod 600 "$tmp" && mv -f "$tmp" "$out"
}

cdev_host_link() {
  local hp=${1:-} proj=${2:-} root=${CLAUDE_ORCA_HOST_LINK_ROOT:-} p target d cur
  [ -n "$hp" ] || { _cdev_sshd_note "host link: no host project dir; not linking"; return 0; }
  p=$hp
  while [[ $p == *//* ]]; do p=${p//\/\//\/}; done
  while [ "${#p}" -gt 1 ] && [[ $p == */ ]]; do p=${p%/}; done
  case $p in
    /) _cdev_sshd_note "host link: refusing '/'"; return 0 ;;
    /*) ;;
    *) _cdev_sshd_note "host link: refusing relative path '$hp'"; return 0 ;;
  esac
  case "/$p/" in
    */../*) _cdev_sshd_note "host link: refusing '$hp' (.. segment)"; return 0 ;;
  esac
  for d in /workspace /home/agent /run /proc /sys /dev /etc /usr /bin /sbin /lib /opt /var /root; do
    if [ "$p" = "$d" ] || [[ $p == "$d"/* ]]; then
      _cdev_sshd_note "host link: refusing '$hp' (under $d)"; return 0
    fi
  done
  target=$root$p
  if [ -L "$target" ]; then
    cur=$(readlink "$target" 2>/dev/null || true)
    if [ "$cur" = "$proj" ]; then
      _cdev_sshd_note "host link: $target already -> $proj"
    else
      _cdev_sshd_note "host link: $target is a symlink to '$cur'; leaving it"
    fi
    return 0
  fi
  if [ -e "$target" ]; then
    _cdev_sshd_note "host link: $target exists and is not a symlink; leaving it"
    return 0
  fi
  if ! ( umask 022; mkdir -p "${target%/*}" ) 2>/dev/null; then
    _cdev_sshd_note "host link: cannot create ${target%/*}; no host link"; return 0
  fi
  if ln -s "$proj" "$target" 2>/dev/null; then
    _cdev_sshd_note "host link: $target -> $proj"
  else
    _cdev_sshd_note "host link: cannot create $target; no host link"
  fi
  return 0
}

cdev_host_key_fpr() {
  local f=${1:-}
  [ -r "$f" ] || return 1
  python3 -I -c '
import base64, hashlib, sys
for line in open(sys.argv[1]):
    w = line.split()
    if len(w) >= 2 and not line.lstrip().startswith("#"):
        blob = base64.b64decode(w[1], validate=True)
        d = base64.b64encode(hashlib.sha256(blob).digest()).decode().rstrip("=")
        print("SHA256:" + d)
        sys.exit(0)
sys.exit(1)' "$f" 2>/dev/null
}

cdev_sshd_probe() {
  local p=${1:-}
  [ -n "$p" ] || return 1
  ( exec 3<>"/dev/tcp/127.0.0.1/$p" && read -r -t 2 -u 3 l && [[ $l == SSH-2.0-* ]] ) 2>/dev/null
}

# The loop's state lives in globals so the TERM trap can reach it.
_cdev_loop_stop() {
  trap '' TERM INT
  [ -n "${_CDEV_LOOP_SLEEPER:-}" ] && kill "$_CDEV_LOOP_SLEEPER" 2>/dev/null
  if [ -n "${_CDEV_LOOP_CHILD:-}" ]; then
    kill "$_CDEV_LOOP_CHILD" 2>/dev/null
    wait "$_CDEV_LOOP_CHILD" 2>/dev/null
  fi
  rm -f "$_CDEV_LOOP_READY"
  exit 0
}

cdev_sshd_loop() {
  local bin=$1 cfg=$2 logf=$3 ready=$4 port=$5 fpr=$6 backoff=1 started dur rc i
  shift 6
  local launcher=("$@")
  _CDEV_LOOP_READY=$ready _CDEV_LOOP_CHILD='' _CDEV_LOOP_SLEEPER=''
  trap _cdev_loop_stop TERM INT
  while :; do
    started=$SECONDS
    ${launcher[@]+"${launcher[@]}"} "$bin" -D -e -f "$cfg" >>"$logf" 2>&1 &
    _CDEV_LOOP_CHILD=$!
    for ((i = 0; i < 25; i++)); do
      kill -0 "$_CDEV_LOOP_CHILD" 2>/dev/null || break
      if cdev_sshd_probe "$port"; then
        printf 'port=%s\nhost_key_sha256=%s\n' "$port" "$fpr" >"$ready.tmp.$$" \
          && mv -f "$ready.tmp.$$" "$ready"
        break
      fi
      sleep 0.2
    done
    rc=0; wait "$_CDEV_LOOP_CHILD" || rc=$?
    rm -f "$ready"
    dur=$((SECONDS - started))
    [ "$dur" -ge 60 ] && backoff=1
    printf 'sshd-loop: sshd exited rc=%s after %ss; restarting in %ss\n' "$rc" "$dur" "$backoff" >>"$logf"
    sleep "$backoff" &
    _CDEV_LOOP_SLEEPER=$!
    wait "$_CDEV_LOOP_SLEEPER" 2>/dev/null
    _CDEV_LOOP_SLEEPER=''
    backoff=$((backoff * 2 > 30 ? 30 : backoff * 2))
  done
}
