#!/usr/bin/env bash
#
# make-launcher-app.sh -- build <project>/Orca.app, the double-clickable
# entry point for a folder (.claude/plans/orca-port.md §9.2). It is a
# five-file stub, not a copy of Orca: Finder launches it, it finds its
# own folder and execs .claude-dev/bin/orca-launch, which is what puts
# the folder's real Orca (under .claude-dev/app) inside the Seatbelt
# profile. Wearing the real app's icon and name is the whole point --
# double-clicking it must feel like opening Orca.
#
# Usage: make-launcher-app.sh --project <dir> [--app <source Orca.app>]
#
# Idempotent: run by `claude-dev register` every time, overwriting its
# own files and nothing else. Degrades instead of failing when the source
# app is not installed yet (registration runs before the DMG on a fresh
# machine): the bundle is still built, just without an icon.
#
# The bundle is host-owned (host-owned-paths.sh) -- write-denied inside
# both sandboxes -- and gitignored, because it is generated per folder.

set -euo pipefail

die() {
    echo "make-launcher-app: $1" >&2
    exit 1
}

# Prints the string value of <key> in the plist <file>, or nothing.
# plutil reads binary plists too and is on every macOS; python3 and the
# sed fallback keep this working on hosts (and test rigs) without it.
read_plist_key() {
    local plist="$1" key="$2" value=""
    [ -f "$plist" ] || return 0
    if command -v plutil >/dev/null 2>&1; then
        value="$(plutil -extract "$key" raw -o - "$plist" 2>/dev/null || true)"
    fi
    if [ -z "$value" ] && command -v python3 >/dev/null 2>&1; then
        value="$(python3 -c 'import plistlib, sys
try:
    print(plistlib.load(open(sys.argv[1], "rb")).get(sys.argv[2], ""))
except Exception:
    pass' "$plist" "$key" 2>/dev/null || true)"
    fi
    if [ -z "$value" ]; then
        value="$(sed -n "/<key>$key<\/key>/{n;s/.*<string>\(.*\)<\/string>.*/\1/p;}" \
            "$plist" 2>/dev/null || true)"
    fi
    printf '%s' "$value"
}

xml_escape() {
    printf '%s' "$1" | sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g'
}

project=""
src_app=""
while [ $# -gt 0 ]; do
    case "$1" in
        --project) project="$2"; shift 2 ;;
        --app)     src_app="$2"; shift 2 ;;
        *) die "unknown argument: $1" ;;
    esac
done

[ -n "$project" ] || die "--project is required"
[ -d "$project" ] || die "project directory does not exist: $project"
project="$(cd "$project" && pwd -P)"
[ -n "$src_app" ] || src_app="$project/.claude-dev/app/Orca.app"

name="$(basename "$project")"
slug="$(printf '%s' "$name" | tr '[:upper:]' '[:lower:]' \
    | sed 's/[^a-z0-9]/-/g' | sed 's/--*/-/g' | sed 's/^-//' | sed 's/-$//')"
[ -n "$slug" ] || slug="project"

bundle="$project/Orca.app"
mkdir -p "$bundle/Contents/MacOS" "$bundle/Contents/Resources"

# The real app's icon, under whatever name its Info.plist gives it
# (electron-builder writes icon.icns; the key is what decides).
icon=""
icon_name="$(read_plist_key "$src_app/Contents/Info.plist" CFBundleIconFile)"
[ -n "$icon_name" ] || icon_name="icon.icns"
case "$icon_name" in
    *.*) ;;
    *) icon_name="$icon_name.icns" ;;
esac
if [ -f "$src_app/Contents/Resources/$icon_name" ]; then
    cp -f "$src_app/Contents/Resources/$icon_name" \
        "$bundle/Contents/Resources/$icon_name"
    icon="$icon_name"
fi

{
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">'
    echo '<plist version="1.0">'
    echo '<dict>'
    echo '	<key>CFBundleName</key>'
    echo "	<string>Orca ($(xml_escape "$name"))</string>"
    echo '	<key>CFBundleDisplayName</key>'
    echo "	<string>Orca ($(xml_escape "$name"))</string>"
    echo '	<key>CFBundleIdentifier</key>'
    echo "	<string>dev.onorca.sandboxed.$slug</string>"
    echo '	<key>CFBundleExecutable</key>'
    echo '	<string>Orca</string>'
    if [ -n "$icon" ]; then
        echo '	<key>CFBundleIconFile</key>'
        echo "	<string>$icon</string>"
    fi
    echo '	<key>CFBundlePackageType</key>'
    echo '	<string>APPL</string>'
    echo '	<key>CFBundleInfoDictionaryVersion</key>'
    echo '	<string>6.0</string>'
    echo '	<key>CFBundleShortVersionString</key>'
    echo '	<string>1.0</string>'
    echo '	<key>CFBundleVersion</key>'
    echo '	<string>1.0</string>'
    echo '	<key>NSHighResolutionCapable</key>'
    echo '	<true/>'
    echo '</dict>'
    echo '</plist>'
} > "$bundle/Contents/Info.plist"

printf 'APPL????' > "$bundle/Contents/PkgInfo"

# Nothing here may depend on PATH or the working directory: Finder
# supplies neither. The folder is three levels above this file, and every
# command used is a shell builtin.
cat > "$bundle/Contents/MacOS/Orca" <<'LAUNCHER'
#!/bin/sh
# Generated by make-launcher-app.sh -- do not edit; rebuilt on every
# `claude-dev register`. Opens this folder's own sandboxed Orca.
self="$0"
case "$self" in
    /*) ;;
    *) self="$PWD/$self" ;;
esac
dir="${self%/*}"        # .../Orca.app/Contents/MacOS
dir="${dir%/*}"         # .../Orca.app/Contents
dir="${dir%/*}"         # .../Orca.app
project="${dir%/*}"     # the project folder
cd "$project" || exit 1
exec "$project/.claude-dev/bin/orca-launch" "$@"
LAUNCHER
chmod 755 "$bundle/Contents/MacOS/Orca"

if [ -z "$icon" ]; then
    echo "Built $bundle (no icon yet: $src_app is not installed)"
else
    echo "Built $bundle"
fi
