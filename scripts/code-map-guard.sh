#!/usr/bin/env bash
# code-map-guard — staged as bin/graphify, i.e. the ONLY `graphify` on PATH
# in this sandbox.
#
# Why a wrapper at all: the upstream graphify CLI mixes two very different
# jobs. Graph work (extract, query, explain, …) is exactly what we want. But
# ~20 per-platform installers (`install`, `claude install`, `hook install`,
# `cursor install`, …) rewrite ASSISTANT CONFIG — CLAUDE.md sections, the
# config dir's hooks and skills, .cursor rules. In this template that config
# is generated and checksum-synced from config/ (scripts/config-sync.sh), so
# anything writing it out-of-band gets silently reverted at the next config
# sync, or worse, sticks around as unexplained drift. The wrapper therefore
# runs deny-by-default: an ALLOWLIST of graph subcommands execs the real
# engine, and everything else — including subcommands upstream adds later —
# exits 2 with a pointer at `code-map`, the project's own front end.
#
# Engine resolution:
#   CODE_MAP_ENGINE, else <host_dir()>/code-map/bin/graphify -- a single,
#   optional, host-owned install shared by every project on this host (see
#   lib/paths.sh's host_dir()); `code-map upgrade` installs there. The env
#   var exists so tests can redirect it.
#
# NOTE: never resolve the engine through PATH (`command -v graphify`) — this
# script IS graphify on PATH, so that would exec itself forever.
#
# Exit: 0/engine's own status when allowed · 2 blocked · 3 no engine found

set -eu

# Resolve through a symlink chain (e.g. bin/graphify -> ../scripts/
# code-map-guard.sh) to this script's real directory, so lib/paths.sh
# resolves whether this is invoked via the repo copy or the
# .claude-dev/template/bin/ symlink.
_resolve_script_path() {
    local src="${BASH_SOURCE[0]}"
    while [ -L "$src" ]; do
        local link dir
        link="$(readlink "$src")"
        case "$link" in
            /*) src="$link" ;;
            *)  dir="$(cd "$(dirname "$src")" && pwd)"; src="$dir/$link" ;;
        esac
    done
    echo "$src"
}
SCRIPT_DIR="$(cd "$(dirname "$(_resolve_script_path)")" && pwd)"
# shellcheck source=lib/paths.sh
. "$SCRIPT_DIR/lib/paths.sh"

_engine_default=""
_host="$(host_dir 2>/dev/null)" && _engine_default="$_host/code-map/bin/graphify"
ENGINE_PATH="${CODE_MAP_ENGINE:-$_engine_default}"

# Block first, resolve second: the deny decision must not depend on which
# engine happens to be installed, and a blocked call must never reach one.
cmd=${1-}

case "$cmd" in
    # graph work — the whole point of shipping the engine
    extract|update|cluster-only|query|explain|path|affected|tree|god-nodes|\
diagnose|label|watch|merge-graphs|merge-driver|export|benchmark|version|help)
        ;;
    # no args / bare flags: let the engine print its own help and version
    ''|--version|--help)
        ;;
    *)
        # name the second token too, so `claude install` doesn't report as
        # bare `claude`
        cat >&2 <<EOF
graphify ${cmd}${2:+ $2} is blocked in this sandbox: it writes assistant config
(CLAUDE.md sections, config-dir hooks and skills, per-platform rules), which is
generated by config sync here and would be reverted or left as drift.

Use \`code-map\` instead. Engine upgrades go through \`code-map upgrade\`.
EOF
        exit 2
        ;;
esac

if [ -n "$ENGINE_PATH" ] && [ -x "$ENGINE_PATH" ]; then
    engine=$ENGINE_PATH
else
    cat >&2 <<EOF
graphify engine not found. Looked for:
  ${ENGINE_PATH:-(no host dir resolvable)}

Run \`code-map doctor\` to diagnose (the engine is an optional host-level
install; a missing one usually means it was never installed on this host).
EOF
    exit 3
fi

exec "$engine" "$@"
